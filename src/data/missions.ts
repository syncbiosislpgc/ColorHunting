export function getMissionById(id: string): MissionDef {
  if (id === FINAL_MISSION_ID) return FINAL_MISSION;
  const found = MISSIONS.find((m) => m.id === id);
  if (!found) throw new Error(`Misión no encontrada: ${id}`);
  return found;
}

export function getPlayableMissionPool(): MissionDef[] {
  return MISSIONS.filter((m) => !m.specialOnly && m.id !== FINAL_MISSION_ID);
}
